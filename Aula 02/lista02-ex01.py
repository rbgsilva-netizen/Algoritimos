# Crie uma lista chamada numeros contendo os valores 10, 20, 30, 40 e 50. Exiba o primeiro, o terceiro e o último elemento da lista.
# Em seguida, exiba a quantidade de elementos.

numeros = [10,20,30,40,50]

print(f'O primeiro elemento da lista é {numeros[0]}')
